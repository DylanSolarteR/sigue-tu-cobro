import { renderToBuffer } from "@react-pdf/renderer";
import { inflateSync } from "node:zlib";
import { expect, it, vi } from "vitest";
import { BillingStatementPDF } from "../../../components/generatePDF";

vi.mock("@/actions/billing-statement.item.api", () => ({
  getBillingStatementItems: vi.fn(),
}));

it("genera un documento PDF real a partir de una cuenta y sus conceptos", async () => {
  const client = { name: "Empresa Ejemplo", docType: "NIT" as const, docNumber: "12345" };
  const creditor = { name: "Persona Ejemplo", docType: "CC" as const, docNumber: "98765" };
  const account = {
    id: "cuenta-1", client_id: "cliente-1", creditor_id: "acreedor-1",
    client, creditor, amount: 125000, showItemAmount: true, status: "pending",
    payDate: "2026-01-01", extraInfo: "Información adicional",
  };
  const items = [{ id: "item-1", billing_statement_id: "cuenta-1", client_id: "cliente-1", status: "added" as const, desc: "Servicio de diseño", amount: 125000 }];

  const pdf = await renderToBuffer(<BillingStatementPDF data={account} items={items} />);
  expect(pdf.subarray(0, 5).toString("ascii")).toBe("%PDF-");
  expect(pdf.subarray(-32).toString("ascii")).toContain("%%EOF");
  expect(pdf.length).toBeGreaterThan(1000);
  const raw = pdf.toString("latin1");
  const fragments: string[] = [];
  for (const stream of raw.matchAll(/stream\r?\n([\s\S]*?)\r?\nendstream/g)) {
    try {
      const content = inflateSync(Buffer.from(stream[1]!, "latin1")).toString("latin1");
      for (const token of content.matchAll(/<([\da-fA-F]+)>/g)) {
        fragments.push(Buffer.from(token[1]!, "hex").toString("latin1"));
      }
    } catch {
      // Non-Flate streams are irrelevant to the text generated by PDFKit.
    }
  }
  const text = fragments.join("");
  expect(text).toContain("EMPRESA EJEMPLO");
  expect(text).toContain("1 de enero de 2026");
  expect(text).toContain("Servicio de dise");
  expect(text).toContain("125.000");
  expect(text.match(/125\.000/g)).toHaveLength(2);
}, 15000);
